#!/usr/bin/env python3
"""Writes src/car_sizes.h: each car's wheelbase and front and rear track (stock body), from the game's databases.

  python tools/gen_car_sizes.py <gamedb.slt> [<more .slt> ...]

Give it the base game's database (Mount\\media\\stripped\\gamedbRC.slt) and those of the car packs (for example
Monument_...\\Mount\\media\\db\\GameDB.slt): a car is taken from the first file that has it. Underglow places the
neon from the car's own lights; this table is for cars whose lights don't span the car (an IndyCar's are all at
the back).
"""
import os, sqlite3, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'car_sizes.h')

cars = {}
for path in sys.argv[1:]:
    db = sqlite3.connect('file:' + path + '?mode=ro', uri=True)
    try:
        rows = db.execute('SELECT u.Ordinal, b.ModelWheelbase, b.ModelFrontTrackOuter, b.ModelRearTrackOuter '
                          'FROM List_UpgradeCarBody u JOIN Data_CarBody b ON b.Id = u.CarBodyID '
                          'WHERE u.IsStock = 1').fetchall()
    except sqlite3.Error as e:
        print('skipped', path, e)
        continue
    n = 0
    for ordinal, wb, ft, rt in rows:
        if ordinal in cars or not wb or not ft or not rt or not (1.5 < wb < 5.0 and 1.0 < ft < 3.0 and 1.0 < rt < 3.0):
            continue
        cars[ordinal] = (wb, ft, rt)
        n += 1
    print('%s: %d car(s)' % (path, n))

lines = ['/* Generated by tools/gen_car_sizes.py from the game\'s databases - do not edit. */',
         '#pragma once', '',
         '/* car ordinal (Data_Car.Id), wheelbase, front track and rear track (outer, meters), stock body; by ordinal */',
         'struct CarSize { int ordinal; float wheelbase, front_track, rear_track; };',
         'const CarSize kCarSizes[] = {']
for o in sorted(cars):
    wb, ft, rt = cars[o]
    lines.append('    {%d, %.3ff, %.3ff, %.3ff},' % (o, wb, ft, rt))
lines.append('};')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('%s: %d car(s)' % (OUT, len(cars)))
