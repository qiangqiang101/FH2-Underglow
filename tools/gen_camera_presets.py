#!/usr/bin/env python3
"""Writes src/camera_presets.h: the game's garage camera shots (Camera.zip\\UICarTargetCameraPresets.xml) with the
Underglow Kit's added, for the mod to hand to the game (platform set_file "Camera/UICarTargetCameraPresets.xml").

  python tools/gen_camera_presets.py <Mount\\media\\Camera.zip>

The kit's rows use copies of game shots (the paint menu's body and rims, the drivetrain and rear wing upgrades)
with the camera's turning held to the shot's angle: unheld, the camera keeps the angle it came with (seen in game:
the rear bumper's showed the car's front). The mod lets go of the hold once the camera is there, so the right stick
turns it. (A wide range instead put every shot at the rear right, seen in game.)
"""
import os, re, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'camera_presets.h')
ADDED = {'LiveryPaintMenu_Body': 'Upgrades_UnderglowBody', 'Upgrades_Drivetrain': 'Upgrades_UnderglowDrivetrain',
         'LiveryPaintMenu_Rims': 'Upgrades_UnderglowRims', 'Upgrades_RearWing': 'Upgrades_UnderglowRearWing',
         'LiveryPaintMenu_Wing': 'Upgrades_UnderglowWing'}

xml = zipfile.ZipFile(sys.argv[1]).read('UICarTargetCameraPresets.xml').decode('utf-8')
extra = []
for src, name in ADDED.items():
    m = re.search(r'<Preset name="%s" ordinal="-1"[^>]*/>' % src, xml)
    if not m:
        sys.exit('no %s in the file' % src)
    p = m.group(0).replace('name="%s"' % src, 'name="%s"' % name)
    p = re.sub(r'enableXAngleRestriction="\d"', 'enableXAngleRestriction="1"', p)
    p = re.sub(r'(min|max)XAngle="[^"]*"', r'\1XAngle="0.000000"', p)
    extra.append('  ' + p)
end = xml.rindex('</UICarTargetCameraPresets>')
out = xml[:end] + '\r\n'.join(extra) + '\r\n' + xml[end:]
data = out.encode('utf-8')

lines = ['/* Generated by tools/gen_camera_presets.py from the game\'s Camera.zip - do not edit. The game\'s garage',
         '   camera shots, with the Underglow Kit\'s: ' + ', '.join(ADDED.values()) + '. */',
         '#pragma once', '', 'const unsigned char kCameraPresets[] = {']
for i in range(0, len(data), 24):
    lines.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
lines.append('};')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('%s: %d bytes, %d shots' % (OUT, len(data), out.count('<Preset')))
