// The LEDs of each level: Lv1 has the [Neon] Side / Front / Rear counts, Lv2 1.5 times, Lv3 twice (10/6/6, 15/9/9,
// 20/12/12 by default).
const float kLedScale[kLedLevels + 1] = {1.0f, 1.0f, 1.5f, 2.0f};
inline int scaled_leds(int lv1, int leds) {
    return int(float(lv1) * kLedScale[leds < 1 ? 1 : leds > kLedLevels ? kLedLevels : leds] + 0.5f);
}
