const int kEnum = 48;
// The rows' part ids. 900480..900487 were the kits before they had LED levels (bought while testing): new ids, so
// the save's old purchases don't count for other rows.
const long kIdBase = 900520;
const int kKits = 8;        // 0 = stock (no underglow), 1..7 = the kits
const int kLedLevels = 3;   // each kit in Lv1..Lv3, with more LEDs
const int kLevels = 1 + (kKits - 1) * kLedLevels;   // the rows: 0 = stock, then each kit's Lv1, Lv2, Lv3
inline int kit_of(int level) { return level <= 0 || level >= kLevels ? 0 : 1 + (level - 1) / kLedLevels; }
inline int leds_of(int level) { return level <= 0 || level >= kLevels ? 0 : 1 + (level - 1) % kLedLevels; }
inline int level_of(int kit, int leds) {
    if (kit <= 0 || kit >= kKits) return 0;
    if (leds < 1) leds = 1;
    if (leds > kLedLevels) leds = kLedLevels;
    return 1 + (kit - 1) * kLedLevels + (leds - 1);
}
const int kTypeId = 7480, kUpgradeBase = 74800, kMotorId = -7480;
const int kArea = 5;           // UpgradeAreas: Aero and Appearance
const int kDisplayOrder = 6;   // after the game's Front Bumper, Rear Wing, Rear Bumper, Side Skirts and Hood (1..5)

