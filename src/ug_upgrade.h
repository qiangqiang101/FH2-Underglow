// The Underglow Kit: a garage upgrade (Garage > Upgrades > Custom upgrade > Aero and Appearance > Underglow Kit),
// bought for each owned car: Stock (no underglow) and 7 kits, each a set of the parts Front, Back and Sides.
//
// The method is NitroSystem II's NOS Kit (Levilente, MIT License; first used by the Universal Wheel Spacers mod),
// written up in NitroSystem-II-FH3/docs/RUNTIME_DB_GUIDE.md. Nothing of the game is changed on disk:
//   - the type and its 8 rows go into the game database through the platform (add_sql: it writes a changed copy to
//     mediaoverride, the original stays as it is),
//   - a few statements the game runs are edited in memory (its database query function is hooked): our rows join
//     the car's upgrade list, the fitted one is marked, and the game's "install" write is swallowed (the kit of each
//     owned car is kept in UnderglowGarage.json instead),
//   - the game's string lookup answers our names (string references no table has),
//   - the game's own getter of the current car's garage id is observed.
//
// Numbers (the guide's registry: Universal Wheel Spacers 45 and 46, NitroSystem 47): part enum 48,
// UpgradeTypes.id 7480, Upgrades.id 74800..74821, part ids 900520..900541, price rows for MotorID -7480, string
// keys 0xA4E0..0xA535 (hash16 0x7E57).
//
// Included by neon_mod.cpp after windows.h and fh2mod.h.
