// ---- The SQL text work: plain string functions --------------------------------------------------------------------

inline const char* find(const char* h, size_t hn, const char* nd) {
    const size_t m = strlen(nd);
    if (!m || hn < m) return nullptr;
    for (size_t i = 0; i + m <= hn; i++)
        if (h[i] == nd[0] && memcmp(h + i, nd, m) == 0) return h + i;
    return nullptr;
}
inline bool starts(const char* s, size_t n, const char* p) {
    const size_t m = strlen(p);
    return n >= m && memcmp(s, p, m) == 0;
}
// digits at p (at most 10, value up to 2147483647) -> value; returns how many digits, 0 if none
inline int num(const char* p, const char* end, long* v) {
    int d = 0;
    unsigned long long x = 0;
    while (p + d < end && p[d] >= '0' && p[d] <= '9' && d < 10) x = x * 10 + unsigned(p[d++] - '0');
    if (x > 2147483647ull) return 0;
    *v = long(x);
    return d;
}
inline void addn(std::string& b, long v) { b += std::to_string(v); }
inline void addref(std::string& b, unsigned key) {
    b += "_&";
    addn(b, long((kStrHash << 16) | key));
}

// 1. CREATE VIEW ...View_UpgradeParts: our rows for the car the view is built for. *ordinal = that car.
inline bool rewrite_view(const char* in, size_t n, std::string& b, long* ordinal, const long price[kLevels]) {
    if (!starts(in, n, "CREATE VIEW")) return false;
    if (!find(in, n < 160 ? n : 160, "View_UpgradeParts AS SELECT 0 AS PartEnum")) return false;
    if (find(in, n, (std::to_string(kIdBase) + " AS PartId").c_str())) return false;
    const char* w = find(in, n, "WHERE Ordinal = ");
    long ord;
    if (!w || !num(w + 16, in + n, &ord) || !ord) return false;
    const char* u = find(in, n, " UNION SELECT ");
    if (!u || u < w) return false;
    b.assign(in, size_t(u - in));
    for (int l = 0; l < kLevels; l++) {
        b += " UNION SELECT ";
        addn(b, kEnum);
        b += " AS PartEnum, ";
        addn(b, kIdBase + l);
        b += " AS PartId, ";
        addn(b, ord);
        b += " AS Ordinal, ";
        addn(b, l == 0);
        b += " AS IsStock, ";
        addn(b, l);
        b += " AS Level, NULL AS ManufacturerID, ";
        addn(b, l ? price[l] : 0);
        b += " AS Price, 0 AS IsException";
    }
    b.append(u, n - size_t(u - in));
    *ordinal = ord;
    return true;
}

// 2. The part list of our type ("SELECT PartTable.PartId AS id ... WHERE PartTable.PartEnum = 48"): *garage = the
// garage id in it (-1 if none).
inline bool is_partlist(const char* in, size_t n, long* garage) {
    if (!starts(in, n, "SELECT PartTable.PartId AS id")) return false;
    const char* p = find(in, n, "WHERE PartTable.PartEnum = ");
    long v;
    if (!p || num(p + 27, in + n, &v) != 2 || v != kEnum) return false;
    *garage = -1;
    const char* g = find(in, n, "purchasedParts.GarageId = ");
    long gv;
    if (g && num(g + 26, in + n, &gv)) *garage = gv;
    return true;
}
// ... with the fitted row being `level`: WHEN PartTable.PartId = N THEN '1'
inline bool rewrite_partlist(const char* in, size_t n, std::string& b, int level) {
    static const char K[] = "WHEN PartTable.PartId = ";
    const char* k = find(in, n, K);
    if (!k) return false;
    const char* at = k + sizeof K - 1;
    if (at < in + n && *at == '-') at++;   // "nothing known is fitted" may come as -1
    long old;
    const int d = num(at, in + n, &old);
    if (!d) return false;
    const char* after = at + d;
    if (!starts(after, size_t(in + n - after), " THEN '1'")) return false;
    b.assign(in, size_t(k - in) + sizeof K - 1);
    addn(b, kIdBase + level);
    b.append(after, size_t(in + n - after));
    return true;
}

// "SELECT 1 From Profile0_Career_PurchasedParts WHERE ... PartEnum = 48 AND PartId = <kIdBase> ...": the game asking
// whether our STOCK row is bought. It must be yes (no: the game looks for a part object our type hasn't, and crashes).
inline bool is_stock_check(const char* in, size_t n) {
    return starts(in, n, "SELECT 1 From Profile0_Career_PurchasedParts") &&
           find(in, n, ("PartEnum = 48 AND PartId = " + std::to_string(kIdBase) + " ").c_str());
}

// 3. Fitting a part: the game writes an unknown type into "UPDATE ...Career_Garage SET MotorParts = <id> WHERE Id =
// <garage>" (no electric motors in FH2). Read the kit and the garage out of it, and make it change nothing.
inline bool rewrite_update(const char* in, size_t n, std::string& b, int* level, long* garage) {
    if (!starts(in, n, "UPDATE ")) return false;
    static const char K[] = " SET MotorParts = ";
    const char* k = find(in, n, K);
    if (!k) return false;
    long id;
    const int d = num(k + sizeof K - 1, in + n, &id);
    if (!d || id < kIdBase || id >= kIdBase + kLevels) return false;
    *level = int(id - kIdBase);
    *garage = -1;
    const char* w = find(k, size_t(in + n - k), " WHERE Id = ");
    long gv;
    if (w && num(w + 12, in + n, &gv)) *garage = gv;
    b.assign(in, size_t(k - in) + sizeof K - 1);
    b += "MotorParts";
    const char* rest = k + sizeof K - 1 + d;
    b.append(rest, size_t(in + n - rest));
    return true;
}

// 4. The rows for the game database (UpgradeTypes, Upgrades, and the price rows), applied at startup.
// `own_icons`: the mod's pictures were handed to the game.
inline std::string database_sql(const long price[kLevels], bool own_icons) {
    const std::string icons = "GAME:\\Media\\UI\\Textures\\Data_Bound\\Upgrade_Parts\\";
    const std::string aero = icons + "Aero_Appearance\\";
    const std::string mine = icons + "Custom\\underglow_";
    auto pic = [&](const char* slot, const char* game) {
        return own_icons ? mine + slot + "_Icon.swatchbin', '" + mine + slot + "_LG_Icon.swatchbin');\n"
                         : aero + game + "_Icon.swatchbin', '" + aero + game + "_LG_Icon.swatchbin');\n";
    };
    std::string b = "INSERT OR REPLACE INTO UpgradeTypes (id, PartEnum, AreaId, IsException, DisplayOrder, "
                    "EverymanUpgradeDisplayOrder, Name, Description, IconPath, ImagePath) VALUES (";
    addn(b, kTypeId);
    b += ", ";
    addn(b, kEnum);
    b += ", ";
    addn(b, kArea);
    b += ", 0, ";
    addn(b, kDisplayOrder);
    b += ", -1, '";
    addref(b, kKeyTypeName);
    b += "', '";
    addref(b, kKeyTypeDesc);
    b += "', '" + pic(kTypeIcon, "aero_appearance");
    // Each kit's tile is the game's own Forza logo, as on the game's Forza race bumpers and wings (part maker 492:
    // Aftermarket_Logos decal146, 200x200 like an upgrade tile); its large picture the car with the kit's glow.
    static const char forza[] = "GAME:\\Media\\UI\\Textures\\Data_Bound\\Aftermarket_Logos\\decal146.swatchbin";
    for (int l = 0; l < kLevels; l++) {
        b += "INSERT OR REPLACE INTO Upgrades (id, TypeId, IsException, Name, Level, Description, IconPath, "
             "ImagePath) VALUES (";
        addn(b, kUpgradeBase + l);
        b += ", '";
        addn(b, kTypeId);
        b += "', 0, '";
        addref(b, kKeyPartName + unsigned(l));
        b += "', ";
        addn(b, l);
        b += ", '";
        addref(b, kKeyPartDesc + unsigned(l));
        b += "', '";
        const int kit = kit_of(l);
        if (!kit) b += icons + "stock_Icon.swatchbin', '" + icons + "stock_LG_Icon.swatchbin');\n";
        else
            b += std::string(forza) + "', '" +
                 (own_icons ? mine + kKitIcons[kit] : aero + kGameIcons[kit]) + "_LG_Icon.swatchbin');\n";
    }
    // The game prices a part of an unknown type from its fallback type's table (SELECT Price FROM
    // List_UpgradeMotorParts WHERE Id = <part id>); with no row the purchase doesn't go through. These are for no
    // motor, so nothing else sees them.
    for (int l = 0; l < kLevels; l++) {
        b += "INSERT OR REPLACE INTO List_UpgradeMotorParts (Id, MotorID, Level, IsStock, ManufacturerID, MassDiff, "
             "WeightDistDiff, Price, TorqueScale) VALUES (";
        addn(b, kIdBase + l);
        b += ", ";
        addn(b, kMotorId);
        b += ", ";
        addn(b, l);
        b += ", ";
        addn(b, l == 0);
        b += ", 0, 0.0, 0.0, ";
        addn(b, l ? price[l] : 0);
        b += ", 1.0);\n";
    }
    return b;
}

